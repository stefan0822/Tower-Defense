using System;
using System.Collections.Generic;
using System.IO;
using UnityEditor;
using UnityEngine;
using UnityEngine.Rendering;

public static class FortressKitUnitySetup
{
    const string Root = "Assets/FortressKit";
    static readonly string[] MaterialNames = {
        "Brick_Rose", "Stone_Sand", "Stone_Light", "Wood_Dark", "Iron_Black",
        "Cloth_Orange", "Paving", "Brick_Dark", "Mortar"
    };
    [MenuItem("Tools/Fortress Kit/1. Setup Materials")]
    public static void SetupMaterials()
    {
        string folder = Root + "/GeneratedMaterials";
        if (!AssetDatabase.IsValidFolder(folder)) AssetDatabase.CreateFolder(Root,"GeneratedMaterials");
        // Determine the ACTIVE render pipeline. A Standard material turns bright
        // magenta in URP/HDRP, even when the texture itself is correct.
        RenderPipelineAsset pipeline = GraphicsSettings.currentRenderPipeline;
        string pipelineType = pipeline == null ? "" : pipeline.GetType().FullName;
        string shaderName;
        if (pipelineType.Contains("Universal"))
            shaderName = "Universal Render Pipeline/Lit";
        else if (pipelineType.Contains("HDRenderPipeline") || pipelineType.Contains("HighDefinition"))
            shaderName = "HDRP/Lit";
        else
            shaderName = "Standard";

        Shader correctShader = Shader.Find(shaderName);
        if (correctShader == null)
        {
            Debug.LogError("Fortress Kit: Shader not found: " + shaderName +
                ". Check that the selected render pipeline is installed and configured.");
            return;
        }
        var mats = new Dictionary<string, Material>();
        foreach (var n in MaterialNames)
        {
            string path = folder + "/" + n + ".mat";
            Material m = AssetDatabase.LoadAssetAtPath<Material>(path);
            if (m == null)
            {
                m = new Material(correctShader); m.name = n;
                AssetDatabase.CreateAsset(m, path);
            }
            else if (m.shader != correctShader)
            {
                // IMPORTANT: Also fix materials generated by older versions of
                // this kit. Merely running the old setup again would not fix them.
                m.shader = correctShader;
            }
            Texture tex = AssetDatabase.LoadAssetAtPath<Texture>(Root + "/Textures/" + n + ".png");
            if (m.HasProperty("_MainTex")) m.SetTexture("_MainTex",tex);
            if (m.HasProperty("_BaseMap")) m.SetTexture("_BaseMap",tex);
            if (m.HasProperty("_BaseColorMap")) m.SetTexture("_BaseColorMap",tex);
            if (m.HasProperty("_Color")) m.SetColor("_Color",Color.white);
            if (m.HasProperty("_BaseColor")) m.SetColor("_BaseColor",Color.white);
            if (m.HasProperty("_Metallic")) m.SetFloat("_Metallic",0f);
            if (m.HasProperty("_Glossiness")) m.SetFloat("_Glossiness",.12f);
            if (m.HasProperty("_Smoothness")) m.SetFloat("_Smoothness",.12f);
            EditorUtility.SetDirty(m);
            mats[n] = m;
        }
        foreach (string guid in AssetDatabase.FindAssets("t:Model",new[]{Root+"/Models"}))
        {
            string path=AssetDatabase.GUIDToAssetPath(guid);
            if (!path.EndsWith(".obj",StringComparison.OrdinalIgnoreCase)) continue;
            var imp=AssetImporter.GetAtPath(path) as ModelImporter;
            if (imp==null) continue;
            foreach (var p in mats)
                imp.AddRemap(new AssetImporter.SourceAssetIdentifier(typeof(Material),p.Key),p.Value);
            imp.SaveAndReimport();
        }
        AssetDatabase.SaveAssets();
        Debug.Log("Fortress Kit materials repaired for " + shaderName + " and remapped.");
    }
    static GameObject Place(Transform root,string mesh,float x,float z,float angle=0,float y=0)
    {
        string path=Root+"/Models/"+mesh+".obj";
        GameObject prefab=AssetDatabase.LoadAssetAtPath<GameObject>(path);
        if (prefab==null) { Debug.LogWarning("Missing "+path); return null; }
        GameObject go=(GameObject)PrefabUtility.InstantiatePrefab(prefab);
        go.name=mesh;
        go.transform.SetParent(root,false);
        go.transform.localPosition=new Vector3(x,y,z);
        go.transform.localRotation=Quaternion.Euler(0,angle,0);
        // Non-convex static MeshColliders, so the gate's arch remains physically open.
        foreach (MeshFilter mf in go.GetComponentsInChildren<MeshFilter>())
        {
            var collider=mf.gameObject.GetComponent<MeshCollider>();
            if(collider==null)collider=mf.gameObject.AddComponent<MeshCollider>();
            collider.sharedMesh=mf.sharedMesh;
        }
        go.isStatic=true;
        return go;
    }
    [MenuItem("Tools/Fortress Kit/2. Create Example Fortress")]
    public static void Build()
    {
        var root=new GameObject("Fortress - Modular Demo");
        foreach (float x in new[]{-12f,12f})
          foreach(float z in new[]{-10f,10f})Place(root.transform,"Tower_Round_Tall",x,z);
        foreach(float x in new[]{-9f,-5f,5f,9f})
           Place(root.transform,Mathf.Abs(x)==9?"Wall_Arrow_Slits_4m":"Wall_Straight_4m",x,-10);
        Place(root.transform,"Gatehouse_Iron_Gate",0,-10);
        foreach(float x in new[]{-10f,-6f,-2f,2f,6f,10f})Place(root.transform,"Wall_Straight_4m",x,10,180);
        foreach(float z in new[]{-8f,-4f,0f,4f,8f})
        { Place(root.transform,"Wall_Straight_4m",-12,z,90);Place(root.transform,"Wall_Straight_4m",12,z,90); }
        Place(root.transform,"Tower_Square",0,6);
        Place(root.transform,"Gatehouse_Banners",0,3.5f,180);
        Place(root.transform,"Tower_Round_Medium",-5,1.2f);
        Place(root.transform,"Tower_Round_Medium",5,1.2f);
        Place(root.transform,"Decoration_Orange_Pennant",-2.7f,-6);
        Place(root.transform,"Decoration_Orange_Pennant",2.7f,-6);
        for(float z=-8;z<3;z+=2)for(float x=-2;x<=2;x+=2)
            Place(root.transform,"Ground_Paving_2m",x,z,0,-.03f);
        if (!AssetDatabase.IsValidFolder(Root+"/Prefabs"))AssetDatabase.CreateFolder(Root,"Prefabs");
        string target=Root+"/Prefabs/Fortress_Modular_Demo.prefab";
        PrefabUtility.SaveAsPrefabAsset(root,target);
        Selection.activeGameObject=root;
        Undo.RegisterCreatedObjectUndo(root,"Create fortress");
        Debug.Log("Built fortress in active scene and saved prefab: "+target);
    }
}
